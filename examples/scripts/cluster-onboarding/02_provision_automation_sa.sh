#!/usr/bin/env bash
# Interactive, Dynamic & Idempotent SA Provisioner
# File: examples/scripts/cluster-onboarding/02_provision_automation_sa.sh
#
# =============================================================================
# TECHNICAL OVERVIEW AND PURPOSE:
#   Idempotent and platform-agnostic automation for onboarding persistent
#   automation identities (ServiceAccount) across the Red Hat OpenShift and
#   K8s cluster fleet. Establishes the Zero-Trust model with permanent Bearer
#   Tokens for integration with the Red Hat Ansible Automation Platform (AAP)
#   and CI/CD pipelines.
#
# STEPS AND PROCESSES PERFORMED:
#   1. Prerequisite Validation: Confirms the existence of the RBAC manifest
#      at files/rbac/ansible-dr-orchestrator-rbac.yaml.
#   2. Session Discovery and Audit: Maps the local KUBECONFIG contexts,
#      filters utility contexts, and tests the validity of the human session
#      (oc whoami).
#   3. Idempotency Validation: Checks whether the permanent context (*-sa) is
#      already configured and functional on the cluster. If so, skips re-execution.
#   4. Scope Selection (Interactive / CLI): Offers a dynamic selection menu or
#      supports non-interactive execution via arguments in automated pipelines.
#   5. Declarative Deployment (oc apply): Provisions the 'ansible-automation'
#      namespace, the ServiceAccount, the cluster-admin ClusterRoleBinding,
#      and the Token Secret.
#   6. KUBECONFIG Registration and Testing: Extracts the Bearer Token, configures
#      the '*-sa-user' user, creates the '*-sa' context, and validates final
#      authentication.
#   7. Fleet Report: Automatically prints the active '-sa' contexts.
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

if ! command -v oc &> /dev/null; then
    echo "❌ [ERROR] The 'oc' binary was not found in the PATH."
    exit 1
fi

MANIFEST_FILE="${REPO_ROOT}/rbac/ansible-dr-orchestrator-rbac.yaml"
NAMESPACE="ansible-automation"
SA_NAME="ansible-dr-orchestrator"
SECRET_NAME="ansible-dr-orchestrator-token"

# Per-cluster credential files directory (used by load_cluster_env.sh and AAP)
CLUSTER_ENV_DIR="${HOME}/.kube/clusters"
mkdir -p "${CLUSTER_ENV_DIR}"

# ---------------------------------------------------------------------------
# write_cluster_env - generates a per-cluster .env file from kubeconfig data
# ---------------------------------------------------------------------------
# Args: $1 = context name (e.g. your-hub-01-sa)
# Reads the server URL, token and CA data from the existing kubeconfig context
# and writes them to ~/.kube/clusters/<context>.env in the format expected by
# examples/scripts/lib/load_cluster_env.sh.
write_cluster_env() {
    local ctx="$1"
    local env_file="${CLUSTER_ENV_DIR}/${ctx}.env"

    # Extract server URL from the kubeconfig context
    local server
    server=$(oc config view --minify --context="${ctx}" -o jsonpath='{.clusters[0].cluster.server}' 2>/dev/null || true)

    # Extract bearer token (raw output to get the actual token, not masked)
    local token
    token=$(oc config view --minify --context="${ctx}" --raw -o jsonpath='{.users[0].user.token}' 2>/dev/null || true)

    # Extract CA data if present (empty for public-CA clusters like ARO)
    local ca_data
    ca_data=$(oc config view --minify --context="${ctx}" --raw -o jsonpath='{.clusters[0].cluster.certificate-authority-data}' 2>/dev/null || true)

    if [ -z "${server}" ] || [ -z "${token}" ]; then
        echo -e "   ${YELLOW}⚠️  Could not extract server/token for ${ctx} - skipping .env file generation.${NC}"
        return 1
    fi

    # Write the .env file with owner-only permissions (contains bearer token)
    cat > "${env_file}" <<EOF
# Cluster: ${ctx}
# Generated by provision_automation_sa.sh
ACM_CLUSTER_HOST=${server}
ACM_CLUSTER_TOKEN=${token}
ACM_CLUSTER_CA_DATA=${ca_data}
ACM_CLUSTER_CONTEXT=${ctx}
EOF
    chmod 600 "${env_file}"
    echo -e "   ${GREEN}📄 Per-cluster env file: ${env_file}${NC}"
}

# Terminal colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

echo -e "${BLUE}============================================================${NC}"
echo -e "${BLUE}  ACM DR - Dynamic & Idempotent SA Provisioner               ${NC}"
echo -e "${BLUE}============================================================${NC}"

if [ ! -f "${MANIFEST_FILE}" ]; then
  echo -e "${RED}❌ [CRITICAL ERROR]: RBAC manifest '${MANIFEST_FILE}' not found!${NC}"
  exit 1
fi

# 1. KUBECONFIG Context Discovery
mapfile -t ALL_CONTEXTS < <(oc config get-contexts -o name 2>/dev/null || true)

if [ ${#ALL_CONTEXTS[@]} -eq 0 ]; then
  echo -e "${RED}❌ [ERROR]: No contexts found in your local KUBECONFIG!${NC}"
  exit 1
fi

echo -e "🔍 Auditing connectivity, authentication, and idempotency of contexts...\n"

VALID_CONTEXTS=()
INVALID_CONTEXTS=()
DISPLAY_LIST=()

declare -A CTX_STATUS
declare -A CTX_USER

# 2. Session Audit and Validation (Pre-flight Audit)
for ctx in "${ALL_CONTEXTS[@]}"; do
  # Skip automation contexts already created with -sa suffix in the initial list
  if [[ "$ctx" == *"-sa" ]]; then
    continue
  fi

  DISPLAY_LIST+=("${ctx}")
  
  # Check whether the corresponding permanent -sa context ALREADY exists and is functional
  SA_CTX_TEST="${ctx}-sa"
  SA_VERIFY=$(oc whoami --context="${SA_CTX_TEST}" 2>/dev/null || true)
  
  if [ "${SA_VERIFY}" == "system:serviceaccount:${NAMESPACE}:${SA_NAME}" ]; then
    CTX_STATUS["${ctx}"]="ALREADY_PROVISIONED"
    CTX_USER["${ctx}"]="${SA_VERIFY}"
    VALID_CONTEXTS+=("${ctx}")
    continue
  fi

  # If no functional -sa exists, check the original human context
  USER_NAME=$(oc whoami --context="${ctx}" 2>/dev/null || true)

  if [ -n "${USER_NAME}" ]; then
    CTX_STATUS["${ctx}"]="VALID"
    CTX_USER["${ctx}"]="${USER_NAME}"
    VALID_CONTEXTS+=("${ctx}")
  else
    CTX_STATUS["${ctx}"]="EXPIRED"
    CTX_USER["${ctx}"]="N/A"
    INVALID_CONTEXTS+=("${ctx}")
  fi
done

# 3. Audit and Idempotency Report Display
echo -e "📋 Status of Contexts Found in KUBECONFIG:"
INDEX=1
for ctx in "${DISPLAY_LIST[@]}"; do
  if [ "${CTX_STATUS[$ctx]}" == "ALREADY_PROVISIONED" ]; then
    echo -e "  [${INDEX}] ${ctx} -> ${CYAN}♻️  CONFIGURED & VALID${NC} (SA: ${ctx}-sa)"
  elif [ "${CTX_STATUS[$ctx]}" == "VALID" ]; then
    echo -e "  [${INDEX}] ${ctx} -> ${GREEN}✅ VALID${NC} (Human User: ${CTX_USER[$ctx]})"
  else
    echo -e "  [${INDEX}] ${ctx} -> ${RED}❌ EXPIRED / NOT AUTHENTICATED${NC}"
  fi
  ((INDEX++))
done

echo ""

# 4. Execution Scope Selection (CLI vs Interactive)
TARGET_CONTEXTS=()

if [ "$#" -gt 0 ]; then
  echo -e "🎯 [NON-INTERACTIVE MODE]: Processing arguments provided via CLI."
  TARGET_CONTEXTS=("$@")
else
  echo -e "🤔 How would you like to proceed?"
  echo -e "   1) Process eligible/valid contexts (${#VALID_CONTEXTS[@]} clusters)"
  echo -e "   2) Select contexts by number (e.g.: 1,3)"
  echo -e "   3) Attempt to process ALL contexts in the list"
  echo -e "   q) Exit"
  echo ""
  read -rp "Your choice [1-3 or q]: " CHOICE

  case "${CHOICE}" in
    1)
      TARGET_CONTEXTS=("${VALID_CONTEXTS[@]}")
      ;;
    2)
      read -rp "Enter the numbers separated by comma (e.g.: 1,3): " NUM_CHOICE
      IFS=',' read -ra ADDR <<< "$NUM_CHOICE"
      for num in "${ADDR[@]}"; do
        num_trimmed=$(echo "$num" | xargs)
        idx=$((num_trimmed - 1))
        if [ $idx -ge 0 ] && [ $idx -lt ${#DISPLAY_LIST[@]} ]; then
          TARGET_CONTEXTS+=("${DISPLAY_LIST[$idx]}")
        else
          echo -e "${YELLOW}⚠️ Invalid option: ${num_trimmed}. Skipping.${NC}"
        fi
      done
      ;;
    3)
      TARGET_CONTEXTS=("${DISPLAY_LIST[@]}")
      ;;
    q|Q)
      echo -e "Operation cancelled by the user."
      exit 0
      ;;
    *)
      echo -e "${RED}Invalid option! Exiting.${NC}"
      exit 1
      ;;
  esac
fi

if [ ${#TARGET_CONTEXTS[@]} -eq 0 ]; then
  echo -e "${YELLOW}⚠️ No contexts selected for processing.${NC}"
  exit 0
fi

echo -e "\n============================================================"
echo -e "🚀 Processing Onboarding / Idempotency for ${#TARGET_CONTEXTS[@]} context(s)..."
echo -e "============================================================"

# 5. Idempotent Onboarding Execution
for ctx in "${TARGET_CONTEXTS[@]}"; do
  echo -e "\n🔍 [ANALYZING]: ${ctx}"

  NEW_CONTEXT="${ctx}-sa"

  # IDEMPOTENCY CHECK: If the -sa context already exists and is functional, skip!
  AUTH_CHECK_IDEMPOTENT=$(oc whoami --context="${NEW_CONTEXT}" 2>/dev/null || true)
  if [ "${AUTH_CHECK_IDEMPOTENT}" == "system:serviceaccount:${NAMESPACE}:${SA_NAME}" ]; then
    echo -e "   ${CYAN}ℹ️  [IDEMPOTENT]: The permanent context '${NEW_CONTEXT}' already exists and is functional.${NC}"
    echo -e "   ${CYAN}   No changes were required on the cluster or KUBECONFIG.${NC}"
    # Generate the per-cluster .env file if it doesn't exist yet
    if [ ! -f "${CLUSTER_ENV_DIR}/${NEW_CONTEXT}.env" ]; then
        write_cluster_env "${NEW_CONTEXT}"
    else
        echo -e "   ${CYAN}📄 Per-cluster env file already exists: ${CLUSTER_ENV_DIR}/${NEW_CONTEXT}.env${NC}"
    fi
    continue
  fi

  # Human session validation before applying
  CHECK_USER=$(oc whoami --context="${ctx}" 2>/dev/null || true)
  if [ -z "${CHECK_USER}" ]; then
    echo -e "   ${RED}❌ [AUTHENTICATION ERROR]: The context '${ctx}' is expired or inactive.${NC}"
    echo -e "   💡 [ACTION REQUIRED]: Renew the session before applying:"
    echo -e "      • OpenShift / ARO : oc login <api-url> -u <user> -p <pass>"
    echo -e "      • Azure Kubernetes Service (AKS) : az aks get-credentials --resource-group <rg> --name <name> --admin"
    echo -e "      • Amazon EKS                    : aws eks update-kubeconfig --region <region> --name <name>"
    echo -e "      • Google Kubernetes Engine (GKE) : gcloud container clusters get-credentials <name> --region <region>"
    echo -e "      • IBM Cloud Kubernetes Svc (IKS) : ibmcloud ks cluster config --cluster <name>"
    continue
  fi

  echo -e "   [+] Active session confirmed: ${GREEN}${CHECK_USER}${NC}"
  echo -e "   [+] Applying RBAC and ServiceAccount declaratively..."

  if ! oc --context="${ctx}" apply -f "${MANIFEST_FILE}" >/dev/null 2>&1; then
    echo -e "   ${RED}❌ [FAILURE]: Unable to apply to '${ctx}'. Please verify cluster-admin permissions.${NC}"
    continue
  fi

  sleep 2

  echo -e "   [+] Extracting permanent Bearer Token..."
  SA_TOKEN=$(oc --context="${ctx}" get secret "${SECRET_NAME}" -n "${NAMESPACE}" -o jsonpath='{.data.token}' 2>/dev/null | base64 -d 2>/dev/null || true)

  if [ -z "${SA_TOKEN}" ]; then
    echo -e "   ${RED}❌ [ERROR]: Failed to extract the token from Secret '${SECRET_NAME}'.${NC}"
    continue
  fi

  CLUSTER_REAL_NAME=$(oc config view -o jsonpath="{.contexts[?(@.name=='${ctx}')].context.cluster}")
  NEW_USER="${ctx}-sa-user"

  echo -e "   [+] Registering permanent context: ${BLUE}[${NEW_CONTEXT}]${NC}"
  oc config set-credentials "${NEW_USER}" --token="${SA_TOKEN}" >/dev/null
  oc config set-context "${NEW_CONTEXT}" --cluster="${CLUSTER_REAL_NAME}" --user="${NEW_USER}" --namespace="${NAMESPACE}" >/dev/null

  # Final Validation Test
  AUTH_VERIFY=$(oc whoami --context="${NEW_CONTEXT}" 2>/dev/null || true)

  if [ "${AUTH_VERIFY}" == "system:serviceaccount:${NAMESPACE}:${SA_NAME}" ]; then
    echo -e "   ${GREEN}✅ [SUCCESS]: Context '${NEW_CONTEXT}' validated as '${AUTH_VERIFY}'.${NC}"
    # Generate the per-cluster .env file alongside the kubeconfig context
    write_cluster_env "${NEW_CONTEXT}"
  else
    echo -e "   ${YELLOW}⚠️  [WARNING]: Context created, but immediate validation failed.${NC}"
  fi
done

# 6. Automatic Display of Active -sa Contexts and Per-Cluster Env Files
echo -e "\n============================================================"
echo -e "🎉 Processing completed successfully!"
echo -e "📋 Active permanent (-sa) contexts in KUBECONFIG:"
echo -e "${BLUE}------------------------------------------------------------${NC}"
if ! oc config get-contexts | grep -- '-sa'; then
  echo -e "${YELLOW}⚠️  No permanent '-sa' context found in KUBECONFIG.${NC}"
fi
echo -e "${BLUE}------------------------------------------------------------${NC}"

# List per-cluster .env files generated during this run
ENV_FILES=("${CLUSTER_ENV_DIR}"/*.env)
if [ -e "${ENV_FILES[0]}" ]; then
  echo -e "\n📄 Per-cluster credential files in ${CLUSTER_ENV_DIR}/:"
  echo -e "${BLUE}------------------------------------------------------------${NC}"
  for ef in "${ENV_FILES[@]}"; do
    echo -e "   ${ef}"
  done
  echo -e "${BLUE}------------------------------------------------------------${NC}"
  echo -e "   Use with: ${CYAN}source examples/scripts/lib/load_cluster_env.sh <role> <file>${NC}"
fi

# Kubeadmin credentials expire quickly and the human login contexts serve no
# purpose once the -sa contexts are working. Leaving them in the kubeconfig
# causes silent auth failures when something tries to reuse them later.
NON_SA_CONTEXTS=$(oc config get-contexts -o name 2>/dev/null | grep -v -- '-sa$' || true)
if [[ -n "${NON_SA_CONTEXTS}" ]]; then
  echo ""
  echo -e "${YELLOW}⚠️  CLEANUP RECOMMENDED:${NC}"
  echo -e "${YELLOW}   The following human login contexts are still in KUBECONFIG:${NC}"
  while IFS= read -r ctx; do
    echo -e "${YELLOW}     - ${ctx}${NC}"
  done <<< "${NON_SA_CONTEXTS}"
  echo -e "${YELLOW}   These use kubeadmin tokens that expire. Remove them now that${NC}"
  echo -e "${YELLOW}   the -sa contexts are validated:${NC}"
  echo ""
  while IFS= read -r ctx; do
    echo -e "   ${CYAN}oc config delete-context \"${ctx}\"${NC}"
  done <<< "${NON_SA_CONTEXTS}"
  echo ""
fi
